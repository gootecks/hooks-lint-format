import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "rumdl" / ".rumdl.toml"
RUMDL_DOCS = ROOT / ".rumdl-docs" / "rules.md"
OUT = ROOT / "docs" / "rumdl-rules.md"

INTRO = """# Rumdl rules in the kit

One row per rule that the pinned rumdl ships. State and fix columns describe `rumdl/.rumdl.toml`: **on** is enabled by default, **opt-in, enabled** is an opt-in rule that the config turns on, **opt-in, off** is an opt-in rule left off. **auto** means the rule fixes every finding, **partial** means it fixes some, **none** means it only reports, **disabled here** means a fix exists and `unfixable` or `fix = false` switches it off while the rule keeps reporting. The reason column is filled for every rule that is off and every fix that is disabled. Policy: [lint-policy.md](lint-policy.md).

Findings without an enabled fix go to the fixer agent (flow in [hk/README.md](../hk/README.md)). Rules that report nothing until a repository sets options: MD043, MD044 (`names`), MD061, MD081. MD042 is listed as fixable by rumdl but leaves empty links unchanged.

This file is generated by `rumdl/rules-table.py` from `rumdl rule`, the opt-in table in the rumdl docs for the same version and `rumdl/.rumdl.toml`. Regenerate it when either changes; do not edit rows by hand.
"""

FIX = {"always available": "auto", "sometimes available": "partial", "not available": "none"}
HEADER = ("ID", "Name", "State", "Fix", "Reason")


def rumdl(*args):
    return subprocess.run(["rumdl", *args], capture_output=True, text=True, check=True).stdout


def fix_false_reasons(lines):
    reasons = {}
    rule = None
    for i, line in enumerate(lines):
        section = re.match(r"\[(MD\d+)\]$", line)
        if section:
            rule = section.group(1)
        elif line.startswith("["):
            rule = None
        elif rule and line.strip() == "fix = false":
            above = lines[i - 1]
            reasons[rule] = above[2:] if above.startswith("# ") else ""
    return reasons


def main():
    if not RUMDL_DOCS.is_file():
        sys.exit(f"{RUMDL_DOCS} is missing; run rumdl/fetch-docs.sh in {ROOT} first")
    text = CONFIG.read_text()
    config = tomllib.loads(text)
    opt_in_table = RUMDL_DOCS.read_text().split("## Opt-in Rules")[1].split("### Enabling")[0]
    opt_in = set(re.findall(r"^\| \[(MD\d+)\]", opt_in_table, re.M))
    unfixable = dict(re.findall(r'^\s+"(MD\d+)",\s*#\s*(.*)$', text, re.M))
    off = dict(re.findall(r"^# (MD\d+) stays off \(opt-in\): (.*)$", text, re.M))
    fix_false = fix_false_reasons(text.splitlines())

    rows = []
    for rule in re.findall(r"^\s+(MD\d+) - ", rumdl("rule"), re.M):
        info = rumdl("rule", rule)
        name = re.search(r"^Name: (.*)$", info, re.M).group(1)
        fix = FIX[re.search(r"^Fix: Fix is (.*)\.$", info, re.M).group(1)]
        state = "on"
        if rule in opt_in:
            state = "opt-in, enabled" if config.get(rule, {}).get("enabled") is True else "opt-in, off"
        reasons = []
        if rule in unfixable:
            fix = "disabled here"
            reasons.append(unfixable[rule])
        elif rule in fix_false:
            fix = "disabled here (opt-in fix)"
            reasons.append(fix_false[rule])
        if rule in off:
            reasons.append(off[rule])
        reason = " ".join(r for r in reasons if r).replace("|", "\\|")
        rows.append((rule, name, state, fix, reason[:1].upper() + reason[1:]))

    missing = [r[0] for r in rows if (r[2] == "opt-in, off" or r[3].startswith("disabled")) and not r[4]]
    if missing:
        sys.exit(f"no reason in {CONFIG} for: {', '.join(missing)}")

    widths = [max(len(r[k]) for r in rows + [HEADER]) for k in range(5)]

    def line(cells):
        return "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths)) + " |"

    table = [line(HEADER), line(tuple("-" * w for w in widths)), *map(line, rows)]
    OUT.write_text(INTRO + "\n" + "\n".join(table) + "\n")
    print(f"{OUT}: {len(rows)} rules")


main()
